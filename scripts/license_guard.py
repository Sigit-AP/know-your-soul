#!/usr/bin/env python3
"""License compliance guard (ATM F-D5, plan section 2 item 4).

Fail-closed verification that the Graphify attribution and the no-verbatim-
copying rule still hold. Every check produces an actionable failure message;
any failure exits non-zero.

Checks (all must pass):

1. ``NOTICE`` exists at the repo root and still contains the strings
   ``Graphify`` and ``Safi Shamsi`` plus the exact dependency pin
   ``graphifyy==<version>`` parsed from ``pyproject.toml`` — the attribution
   and the observed-version pin must stay auditable together.
2. ``pyproject.toml`` declares ``license-files`` covering ``NOTICE``, and
   the ``LICENSE`` file itself exists.
3. No forbidden Graphify marker phrase appears anywhere in ``src/**/*.py``
   (copied/moved-verbatim markers, generator headers, upstream copyright
   headers). Naming the ``graphify`` package in imports or docstrings is
   legitimate and is not flagged.

Usage: ``python scripts/license_guard.py [--root PATH]`` (default: the
repository root containing this script).
"""

from __future__ import annotations

import argparse
import re
import sys
import tomllib
from pathlib import Path

__all__ = ["FORBIDDEN_PATTERNS", "main", "run_guard"]

# Marker phrases that must never appear in our sources. Kept deliberately
# specific so legitimate references (``import graphify`` in the adapter,
# prose about the dependency) never trip the guard.
FORBIDDEN_PATTERNS: tuple[str, ...] = (
    "copied verbatim from graphify",
    "moved verbatim from graphify",
    "generated by /graphify",
    "copyright 2026 safi shamsi",
    "copyright (c) 2026 safi shamsi",
)

_REQUIRED_NOTICE_STRINGS = ("Graphify", "Safi Shamsi")
_GRAPHIFY_DEP_RE = re.compile(r"^graphifyy(?:\[[^\]]*\])?==([0-9][A-Za-z0-9.\-+]*)$")


def _check_notice(root: Path, expected_pin: str | None) -> list[str]:
    failures: list[str] = []
    notice = root / "NOTICE"
    if not notice.is_file():
        return ["NOTICE is missing from the repository root; restore the Graphify attribution file"]
    text = notice.read_text(encoding="utf-8")
    for needle in _REQUIRED_NOTICE_STRINGS:
        if needle not in text:
            failures.append(f"NOTICE no longer contains {needle!r}; the Graphify attribution must be preserved")
    if expected_pin is not None and f"graphifyy=={expected_pin}" not in text:
        failures.append(
            f"NOTICE does not record the pinned dependency version 'graphifyy=={expected_pin}' "
            "(pin it in NOTICE so the attribution stays auditable)"
        )
    return failures


def _check_pyproject(root: Path) -> tuple[list[str], str | None]:
    failures: list[str] = []
    expected_pin: str | None = None
    pyproject = root / "pyproject.toml"
    if not pyproject.is_file():
        return ["pyproject.toml is missing"], None
    try:
        data = tomllib.loads(pyproject.read_text(encoding="utf-8"))
    except tomllib.TOMLDecodeError as error:
        return [f"pyproject.toml does not parse: {error}"], None
    project = data.get("project")
    if not isinstance(project, dict):
        return ["pyproject.toml has no [project] table"], None

    license_files = project.get("license-files")
    if not isinstance(license_files, list) or "NOTICE" not in license_files:
        failures.append("pyproject.toml license-files must include \"NOTICE\" so distributions ship the attribution")
    if not (root / "LICENSE").is_file():
        failures.append("LICENSE is missing from the repository root")

    dependencies = project.get("dependencies", [])
    if isinstance(dependencies, list):
        for dependency in dependencies:
            if not isinstance(dependency, str) or not dependency.startswith("graphifyy"):
                continue
            match = _GRAPHIFY_DEP_RE.match(dependency)
            if match is None:
                failures.append(
                    f"dependency {dependency!r} is not an exact == pin; the Graphify dependency must stay pinned"
                )
            else:
                expected_pin = match.group(1)
    if expected_pin is None and not any("graphifyy" in failure for failure in failures):
        failures.append("pyproject.toml declares no pinned graphifyy dependency to attribute")
    return failures, expected_pin


def _check_src(root: Path) -> list[str]:
    failures: list[str] = []
    src = root / "src"
    if not src.is_dir():
        return failures
    for path in sorted(src.rglob("*.py")):
        try:
            lines = path.read_text(encoding="utf-8").splitlines()
        except (OSError, UnicodeDecodeError) as error:
            failures.append(f"{path.relative_to(root)}: unreadable source file: {error}")
            continue
        for lineno, line in enumerate(lines, start=1):
            lowered = line.lower()
            for pattern in FORBIDDEN_PATTERNS:
                if pattern in lowered:
                    failures.append(
                        f"{path.relative_to(root)}:{lineno}: forbidden Graphify marker {pattern!r}; "
                        "re-implementations must be clean-room (plan section 2)"
                    )
    return failures


def run_guard(root: Path) -> list[str]:
    """Run every check under *root*; return all failure messages (empty = OK)."""
    pyproject_failures, expected_pin = _check_pyproject(root)
    failures = list(pyproject_failures)
    failures.extend(_check_notice(root, expected_pin))
    failures.extend(_check_src(root))
    return failures


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="License compliance guard (ATM F-D5)")
    parser.add_argument(
        "--root",
        type=Path,
        default=Path(__file__).resolve().parents[1],
        help="repository root to verify (default: the parent of this script)",
    )
    args = parser.parse_args(argv)
    failures = run_guard(args.root)
    if failures:
        for failure in failures:
            print(f"license-guard: FAIL: {failure}", file=sys.stderr)
        return 1
    print(f"license-guard: OK (root {args.root})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
