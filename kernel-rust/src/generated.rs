//! Generated/minified detection — a byte-faithful port of the Python
//! reference (`know_your_soul.ingest.extractor.detect_generated`), which is
//! itself a port of codegraph `generated-detection.ts`. Relevance hint only.

use regex::Regex;

const GENERATED_NAME_MARKERS: &[&str] = &[
    ".pb.go",
    "_grpc.pb.go",
    "_mock.go",
    "_mocks.go",
    ".generated.js",
    ".generated.ts",
    ".gen.js",
    ".gen.ts",
    ".pb.js",
    ".pb.ts",
    "-min.js",
    ".min.js",
    "_pb2.py",
    ".pb.cc",
    ".pb.h",
    ".g.cs",
    "grpc.cs",
    ".generated.rs",
    ".pb.swift",
    ".g.dart",
    ".freezed.dart",
];

const BANNER_SCAN_CHARS: usize = 8192;
const BANNER_SCAN_LINES: usize = 60;
const COMMENT_LEADERS: &[&str] = &["#", "//", "/*", "*", "<!--", "--", ";", "%"];

const MINIFIED_MIN_BYTES: usize = 4096;
const MINIFIED_LONG_LINE: usize = 1000;
const MINIFIED_LONG_LINE_FRACTION: f64 = 0.5;
const MINIFIED_PUNCTUATION_FRACTION: f64 = 0.03;
const MINIFIED_PUNCTUATION: &[char] = &[';', '{', '}', '(', ')', ','];

fn banner_patterns() -> &'static [Regex] {
    static PATTERNS: std::sync::OnceLock<Vec<Regex>> = std::sync::OnceLock::new();
    PATTERNS.get_or_init(|| {
        [
            r"code generated\b.*\bdo not edit",
            r"@generated\b",
            r"<auto-generated>",
            r"\bauto-generated\b",
            r"automatically generated",
        ]
        .iter()
        .map(|pattern| Regex::new(pattern).expect("banner patterns must compile"))
        .collect()
    })
}

fn is_generated_name(path: &str) -> bool {
    let lowered = path.to_lowercase();
    let name = lowered.rsplit('/').next().unwrap_or(&lowered);
    GENERATED_NAME_MARKERS.iter().any(|marker| name.ends_with(marker))
}

fn has_generated_banner(source: &str) -> bool {
    let lines: Vec<&str> = source.split('\n').take(BANNER_SCAN_LINES).collect();
    let joined = lines.join("\n");
    // Python: head = joined[:8192] — chars, not bytes.
    let head: String = joined.chars().take(BANNER_SCAN_CHARS).collect();
    if !head.to_lowercase().contains("generat") {
        return false;
    }
    let mut in_block_comment = false;
    for raw_line in head.split('\n') {
        let line = raw_line.trim().to_lowercase();
        if line.contains("/*") {
            let after = line.splitn(2, "/*").nth(1).unwrap_or("");
            if !after.contains("*/") {
                in_block_comment = true;
            }
        }
        let is_comment =
            in_block_comment || COMMENT_LEADERS.iter().any(|leader| line.starts_with(leader));
        if is_comment && banner_patterns().iter().any(|pattern| pattern.is_match(&line)) {
            return true;
        }
        if line.contains("*/") {
            in_block_comment = false;
        }
    }
    false
}

fn is_minified(path: &str, source: &str) -> bool {
    let lowered = path.to_lowercase();
    let suffix = if lowered.contains('.') {
        format!(".{}", lowered.rsplit('.').next().unwrap_or(""))
    } else {
        String::new()
    };
    if !matches!(suffix.as_str(), ".js" | ".mjs" | ".cjs") {
        return false;
    }
    // Python len(str) counts codepoints, not bytes.
    let source_len = source.chars().count();
    if source_len < MINIFIED_MIN_BYTES {
        return false;
    }
    let mut long_line_chars = 0usize;
    let mut punctuation = 0usize;
    for line in source.split('\n') {
        let line_len = line.chars().count();
        if line_len >= MINIFIED_LONG_LINE {
            long_line_chars += line_len;
            punctuation += line.chars().filter(|ch| MINIFIED_PUNCTUATION.contains(ch)).count();
        }
    }
    if (long_line_chars as f64) < MINIFIED_LONG_LINE_FRACTION * (source_len as f64) {
        return false;
    }
    (punctuation as f64) >= MINIFIED_PUNCTUATION_FRACTION * (long_line_chars as f64)
}

pub fn detect_generated(path: &str, source: &str) -> bool {
    is_generated_name(path) || has_generated_banner(source) || is_minified(path, source)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn name_markers() {
        assert!(is_generated_name("pkg/api.pb.go"));
        assert!(is_generated_name("bundle.min.js"));
        assert!(!is_generated_name("src/main.rs"));
    }

    #[test]
    fn banner_requires_comment_context() {
        assert!(has_generated_banner("// Code generated by tool. DO NOT EDIT.\npackage x\n"));
        assert!(!has_generated_banner("let s = \"code generated do not edit\";\n"));
        assert!(has_generated_banner("/*\n * @generated\n */\n"));
    }

    #[test]
    fn minified_detection() {
        let long_line = "a;".repeat(1500);
        let source = format!("{long_line}\n{long_line}");
        assert!(is_minified("bundle.js", &source));
        assert!(!is_minified("bundle.py", &source));
        assert!(!is_minified("bundle.js", "short\n"));
    }
}
