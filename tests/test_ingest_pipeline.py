            pipeline.ingest_path(tmp_path, resolve=False)  # observe the parked resurrected ref
            pending = store.pending_unresolved_refs()
            assert len(pending) == 1
            assert pending[0].target_name == "beta"
            assert pending[0].kind == "calls"
            alpha = make_node_id(path="a.py", kind="function", name="alpha", line=1)
