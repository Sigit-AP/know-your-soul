class TestPathDiscipline:
    def test_missing_path_typed(self, tmp_path):
        from know_your_soul.store import EventStore

        with EventStore() as store:
            pipeline = make_pipeline(store)
            with pytest.raises(PathNotFoundError) as excinfo:
                pipeline.ingest_path(tmp_path / "nope")
            assert excinfo.value.code == "PATH_NOT_FOUND"

    def test_missing_path_still_audits(self, tmp_path):
        from know_your_soul.store import EventStore

        with EventStore(str(tmp_path / "s.sqlite3")) as store:
            pipeline = make_pipeline(store)
            with pytest.raises(PathNotFoundError):
                pipeline.ingest_path(tmp_path / "nope")
            with store.read() as conn:
                rows = conn.execute("SELECT event_type, payload_json FROM event_log WHERE kind='audit'").fetchall()
            assert len(rows) == 1
            payload = json.loads(str(rows[0]["payload_json"]))
            assert payload["status"] == "failure"

    def test_single_file_mode(self, tmp_path):
        from know_your_soul.store import EventStore

        write_fixture(tmp_path, SIMPLE)
        with EventStore() as store:
            report = make_pipeline(store).ingest_path(tmp_path / "a.py")
            assert report.status == "proposal"
            assert report.stats["proposed"] == 1
            assert report.totals["nodes"] == 1 + 2  # file node + alpha + beta

    def test_symlink_escape_per_file_failure(self, tmp_path):
        from know_your_soul.store import EventStore

        outside = tmp_path / "outside"
        outside.mkdir()
        (outside / "secret.py").write_text("def hidden():\n    pass\n", encoding="utf-8")
        root = tmp_path / "root"
        root.mkdir()
        (root / "ok.py").write_text("def fine():\n    pass\n", encoding="utf-8")
        (root / "link.py").symlink_to(outside / "secret.py")
        with EventStore() as store:
            report = make_pipeline(store).ingest_path(root)
            by_rel = {entry.relpath: entry for entry in report.files}
            assert by_rel["link.py"].status == "failed"
            assert by_rel["link.py"].error_code == "PATH_OUTSIDE_ROOT"
            assert by_rel["ok.py"].status == "proposed"
            assert report.stats["failed"] == 1

    def test_single_file_outside_nothing(self, tmp_path):
        """A directly-named file is its own root scope: it can always be read."""
        from know_your_soul.store import EventStore

        write_fixture(tmp_path, {"solo.py": "def solo():\n    pass\n"})
        with EventStore() as store:
            report = make_pipeline(store).ingest_path(tmp_path / "solo.py")
            assert report.stats["proposed"] == 1

    def test_outside_root_error_type_exists(self):
        assert issubclass(PathOutsideRootError, Exception)
        assert PathOutsideRootError("x").code == "PATH_OUTSIDE_ROOT"
        assert PathNotReadableError("x").code == "PATH_NOT_READABLE"

    def test_unreadable_file_typed(self, tmp_path, monkeypatch):
        from know_your_soul.store import EventStore

        write_fixture(tmp_path, SIMPLE)
        original = Path.read_bytes

        def guarded(self):
            if self.name == "a.py":
                raise PermissionError("denied")
            return original(self)

        monkeypatch.setattr(Path, "read_bytes", guarded)
        with EventStore() as store:
            report = make_pipeline(store).ingest_path(tmp_path)
            by_rel = {entry.relpath: entry for entry in report.files}
            assert by_rel["a.py"].status == "failed"
            assert by_rel["a.py"].error_code == "PATH_NOT_READABLE"
            assert by_rel["b.py"].status == "proposed"

    def test_directory_itself_not_readable(self, tmp_path, monkeypatch):
        from know_your_soul.store import EventStore

        write_fixture(tmp_path, SIMPLE)
        monkeypatch.setattr(Path, "is_dir", lambda self: (_ for _ in ()).throw(PermissionError("denied")))
        with EventStore() as store:
            with pytest.raises(PathNotReadableError):
                make_pipeline(store).ingest_path(tmp_path)


