# ------------------------------------------------------------------ helpers


def make_pipeline(store, *, extractor=None, resolver=None, budget=None, thresholds=None):
    return IngestionPipeline(
        store,
        extractor=extractor if extractor is not None else ToyExtractor(),
        resolver=resolver if resolver is not None else ToyResolver(),
        budget=budget if budget is not None else IngestionBudget(),
        split_thresholds=thresholds,
    )


def file_sha(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


SIMPLE = {
    "a.py": "def alpha():\n    pass\n\ndef beta():\n    pass\n",
    "b.py": "class Gamma:\n    pass\n",
}


